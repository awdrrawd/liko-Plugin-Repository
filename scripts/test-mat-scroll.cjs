const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const freeze = fs.readFileSync('Plugins/expand/BC_ChatScrollFreeze.js', 'utf8');
const source = fs.readFileSync('Plugins/main/Liko - MAT.main.user.js', 'utf8');
const scroll = freeze.slice(freeze.indexOf('	function onScroll()'), freeze.indexOf('\n	/** 綁定 scroll'));
const log = { clientHeight: 100, scrollHeight: 500, scrollTop: 0 };
const ctx = vm.createContext({ log, Date, frozen: false, replaying: false, lastClientHeight: 100, suppressFreezeUntil: 0, scrollIntentUntil: 0, suppressExitUntil: 0, FREEZE_THRESHOLD: .05, shown: 0, getChatLog: () => log, distanceFromBottomRatio: () => 1, isAtBottom: () => false });
vm.runInContext('function showSearchBar(){shown++;} ' + scroll, ctx);
vm.runInContext('onScroll()', ctx);
assert.equal(ctx.frozen, false, 'translation/layout scroll must not freeze');
ctx.scrollIntentUntil = Date.now() + 1500;
vm.runInContext('onScroll()', ctx);
assert.equal(ctx.frozen, true, 'intentional history scrolling freezes');
assert.equal(ctx.shown, 1);
const show = freeze.slice(freeze.indexOf('	function showSearchBar()'), freeze.indexOf('\n	function closeSearchBar()'));
assert.ok(show.includes('if (!frozen || disposed) return;')); 
assert.equal((show.match(/input\.focus\(\)/g) || []).length, 1, 'only explicit Clear button may focus search');
const follow = source.slice(source.indexOf('    function scrollChatToEndIfWasAtEnd'), source.indexOf('    // ============================================================', source.indexOf('    function scrollChatToEndIfWasAtEnd')));
const followCtx = vm.createContext({ window: {Liko:{__Sys_ChatScrollFreeze__:{isFrozen:()=>false}}}, document:{querySelector:()=>log} });
vm.runInContext(follow + ';scrollChatToEndIfWasAtEnd(true)', followCtx);
assert.equal(log.scrollTop, 500, 'follow bottom synchronously');
log.scrollTop=40;
followCtx.window.Liko.__Sys_ChatScrollFreeze__.isFrozen=()=>true;
vm.runInContext('scrollChatToEndIfWasAtEnd(true)', followCtx);
assert.equal(log.scrollTop,40,'preserve frozen viewport');
console.log('MAT scroll/focus regression checks passed.');
